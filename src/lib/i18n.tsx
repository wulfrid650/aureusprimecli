const localeDateMap: Record<Locale, string> = {
  fr: "fr-FR",
  en: "en-US",
};

type I18nContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: TranslateFn;
  dateLocale: string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

function readNestedValue(source: unknown, key: string): unknown {
  return key.split(".").reduce<unknown>((current, part) => {
    if (current && typeof current === "object" && part in current) {
      return (current as Record<string, unknown>)[part];
    }

    return undefined;
  }, source);
}

function interpolate(template: string, values?: TranslateValues): string {
  if (!values) {
    return template;
  }

  return template.replace(/\{(\w+)\}/g, (match, key) => String(values[key] ?? match));
}

function applyLocale(locale: Locale) {
  document.documentElement.lang = locale;
  document.documentElement.dataset.locale = locale;
}

async function persistUserLocale(locale: Locale) {
  if (!getStoredAuthToken()) {
    return;
  }

  try {
    await apiFetch("/api/v1/me/profile", {
      method: "PATCH",
      body: JSON.stringify({ locale }),
    });
  } catch (error) {
    console.warn("[i18n] Failed to persist locale preference:", error);
  }
}

export function getDateLocale(locale: Locale): string {
  return localeDateMap[locale];
}

export function getPlural(locale: Locale, count: number): string {
  return locale === "fr" ? (Math.abs(count) > 1 ? "s" : "") : Math.abs(count) === 1 ? "" : "s";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("fr");

  useEffect(() => {
    const nextLocale = resolveClientLocale();

    persistClientLocale(nextLocale);
    applyLocale(nextLocale);
    window.queueMicrotask(() => setLocaleState(nextLocale));
  }, []);

  const setLocale = useCallback((nextLocale: Locale) => {
    setLocaleState(nextLocale);
    persistClientLocale(nextLocale);
    applyLocale(nextLocale);
    void persistUserLocale(nextLocale);
  }, []);

  const t = useCallback<TranslateFn>(
    (key, values) => {
      const localizedValue = readNestedValue(dictionaries[locale], key);
      const fallbackValue = readNestedValue(dictionaries.fr, key);
      const value = typeof localizedValue === "string" ? localizedValue : fallbackValue;

      return typeof value === "string" ? interpolate(value, values) : key;
    },
    [locale],
  );

  const value = useMemo<I18nContextValue>(
    () => ({
      locale,
      setLocale,
      t,
      dateLocale: localeDateMap[locale],
    }),
    [locale, setLocale, t],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const value = useContext(I18nContext);

  if (!value) {
    throw new Error("useI18n must be used inside I18nProvider");
  }

  return value;
}
